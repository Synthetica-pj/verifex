import os
from PIL import Image

master_dir = "/content/dataset_work"
MIN_WIDTH, MIN_HEIGHT = 299, 299
MIN_FILE_SIZE_KB = 10

print("Step 1: Removing low-quality images...")

for category in ["Real", "Fake"]:
    path = os.path.join(master_dir, category)
    files = os.listdir(path)
    removed_count = 0

    for f in files:
        file_path = os.path.join(path, f)
        try:
            if os.path.getsize(file_path) < MIN_FILE_SIZE_KB * 1024:
                os.remove(file_path)
                removed_count += 1
                continue

            with Image.open(file_path) as img:
                width, height = img.size
                if width < MIN_WIDTH or height < MIN_HEIGHT:
                    os.remove(file_path)
                    removed_count += 1
        except:
            os.remove(file_path)
            removed_count += 1

    print(f"Removed {removed_count} low-quality images from {category}.")

real_files = sorted(os.listdir(os.path.join(master_dir, "Real")))
fake_files = sorted(os.listdir(os.path.join(master_dir, "Fake")))

target_count = min(len(real_files), len(fake_files))

print(f"Step 2: Balancing datasets to {target_count} images each...")

if len(real_files) > target_count:
    for f in real_files[target_count:]:
        os.remove(os.path.join(master_dir, "Real", f))

elif len(fake_files) > target_count:
    for f in fake_files[target_count:]:
        os.remove(os.path.join(master_dir, "Fake", f))

print(f"Success! Your dataset is now balanced at {target_count} Real and {target_count} Fake images.")

