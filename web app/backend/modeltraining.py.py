import numpy as np
import cv2
import matplotlib.pyplot as plt
import tensorflow as tf

def get_verdict(img_path, model):
    img = tf.keras.preprocessing.image.load_img(img_path, target_size=(299, 299))
    img_array = tf.keras.preprocessing.image.img_to_array(img) / 255.0
    img_batch = np.expand_dims(img_array, axis=0)

    prediction = model.predict(img_batch)[0][0]
    score = prediction * 100 if prediction > 0.5 else (1 - prediction) * 100
    label = "FAKE" if prediction > 0.5 else "REAL"

    explanation = ""
    if prediction > 0.8:
        explanation = "High confidence of AI manipulation. The model detected strong artificial artifacts in facial textures."
    elif prediction > 0.5:
        explanation = "Moderate suspicion of tampering. Minor irregularities found in pixel consistency."
    else:
        explanation = "High confidence this image is REAL. Skin textures and edges appear natural and consistent."

    plt.imshow(img)
    plt.title(f"Verdict: {label} ({score:.2f}%)\n{explanation}")
    plt.axis('off')
    plt.show()

